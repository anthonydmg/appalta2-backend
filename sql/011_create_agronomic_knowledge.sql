BEGIN;

DROP SCHEMA IF EXISTS agronomic_knowledge CASCADE;
CREATE SCHEMA agronomic_knowledge;

CREATE TABLE agronomic_knowledge.pest_species (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scientific_name TEXT NOT NULL UNIQUE,
    common_name TEXT,
    pest_family TEXT,
    host_crop TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE agronomic_knowledge.scientific_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    authors TEXT[] NOT NULL DEFAULT '{}',
    publication_year SMALLINT,
    institution TEXT,
    document_type TEXT,
    country TEXT,
    document_url TEXT,
    local_storage_path TEXT,
    extraction_status TEXT NOT NULL DEFAULT 'EXTRACTED_PENDING_AGRONOMIC_VALIDATION',
    raw_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE agronomic_knowledge.scientific_studies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL UNIQUE
        REFERENCES agronomic_knowledge.scientific_sources(id) ON DELETE CASCADE,
    pest_id BIGINT NOT NULL
        REFERENCES agronomic_knowledge.pest_species(id) ON DELETE RESTRICT,
    study_type TEXT,
    crop TEXT,
    crop_variety TEXT,
    study_location TEXT,
    study_locations JSONB NOT NULL DEFAULT '[]'::jsonb,
    study_period TEXT,
    methodology TEXT,
    limitations JSONB NOT NULL DEFAULT '[]'::jsonb,
    raw_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_study_locations_array CHECK (jsonb_typeof(study_locations) = 'array')
);

CREATE TABLE agronomic_knowledge.study_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL
        REFERENCES agronomic_knowledge.scientific_studies(id) ON DELETE CASCADE,
    condition_code TEXT NOT NULL UNIQUE,
    controlled_environment BOOLEAN,
    conditions_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_conditions_object CHECK (jsonb_typeof(conditions_data) = 'object')
);

CREATE TABLE agronomic_knowledge.scientific_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL
        REFERENCES agronomic_knowledge.scientific_studies(id) ON DELETE CASCADE,
    condition_id BIGINT
        REFERENCES agronomic_knowledge.study_conditions(id) ON DELETE SET NULL,
    evidence_code TEXT NOT NULL UNIQUE,
    climate_variable TEXT NOT NULL,
    biological_response TEXT NOT NULL,
    finding TEXT NOT NULL,
    result_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    evidence_type TEXT,
    statistical_support TEXT,
    source_location JSONB NOT NULL DEFAULT '{}'::jsonb,
    interpretation_limit TEXT,
    validation_status TEXT NOT NULL DEFAULT 'EXTRACTED_PENDING_AGRONOMIC_VALIDATION',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_result_object CHECK (jsonb_typeof(result_data) = 'object'),
    CONSTRAINT ck_source_location_object CHECK (jsonb_typeof(source_location) = 'object')
);


CREATE INDEX idx_studies_pest_id
    ON agronomic_knowledge.scientific_studies(pest_id);
CREATE INDEX idx_studies_study_type
    ON agronomic_knowledge.scientific_studies(study_type);
CREATE INDEX idx_studies_locations_gin
    ON agronomic_knowledge.scientific_studies USING GIN(study_locations);
CREATE INDEX idx_conditions_study_id
    ON agronomic_knowledge.study_conditions(study_id);
CREATE INDEX idx_conditions_data_gin
    ON agronomic_knowledge.study_conditions USING GIN(conditions_data);
CREATE INDEX idx_evidence_study_id
    ON agronomic_knowledge.scientific_evidence(study_id);
CREATE INDEX idx_evidence_climate_variable
    ON agronomic_knowledge.scientific_evidence(climate_variable);
CREATE INDEX idx_evidence_biological_response
    ON agronomic_knowledge.scientific_evidence(biological_response);
CREATE INDEX idx_evidence_validation_status
    ON agronomic_knowledge.scientific_evidence(validation_status);
CREATE INDEX idx_evidence_result_data_gin
    ON agronomic_knowledge.scientific_evidence USING GIN(result_data);

COMMENT ON SCHEMA agronomic_knowledge IS
    'Base de conocimiento científico agronómico de Appalta.';
COMMENT ON COLUMN agronomic_knowledge.scientific_studies.study_location IS
    'Resumen textual del lugar principal de ejecución u observación del estudio.';
COMMENT ON COLUMN agronomic_knowledge.scientific_studies.study_locations IS
    'Lista JSONB de ubicaciones con roles diferenciados: ejecución, origen de material biológico, vivero de plantones u observación de campo.';
COMMENT ON COLUMN agronomic_knowledge.study_conditions.conditions_data IS
    'Condiciones originales de cada evidencia, conservadas en JSONB sin forzar variables heterogéneas a columnas fijas.';
COMMENT ON COLUMN agronomic_knowledge.scientific_evidence.result_data IS
    'Resultado cuantitativo/cualitativo original conservado en JSONB.';

COMMIT;


UPDATE agronomic_knowledge.scientific_studies st
SET study_locations = (
    SELECT jsonb_agg(
        CASE
            WHEN loc->>'role' = 'field_observation_site'
                 AND loc->>'district' = 'Motupe'
            THEN jsonb_set(
                loc,
                '{province}',
                '"Lambayeque"'::jsonb,
                true
            )
            ELSE loc
        END
        ORDER BY ordinality
    )
    FROM jsonb_array_elements(st.study_locations)
         WITH ORDINALITY AS item(loc, ordinality)
)
FROM agronomic_knowledge.scientific_sources src
WHERE src.id = st.source_id
  AND src.document_code = 'F05'
  AND EXISTS (
      SELECT 1
      FROM jsonb_array_elements(st.study_locations) loc
      WHERE loc->>'role' = 'field_observation_site'
        AND loc->>'district' = 'Motupe'
        AND loc->>'province' IS NULL
  );