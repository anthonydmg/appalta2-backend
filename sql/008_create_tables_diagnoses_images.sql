-- ============================================================
-- 1. EXTENSIONES
-- ============================================================

-- Android genera los UUID antes de sincronizar.
-- No es obligatorio generar UUID desde PostgreSQL.

-- No se necesita pgcrypto: Android genera los UUID.


-- ============================================================
-- 2. FUNCION PARA ACTUALIZAR updated_at
-- ============================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ============================================================
-- 3. TABLA: images
-- Almacena las referencias a las imagenes optimizada y original.
-- ============================================================

CREATE TABLE IF NOT EXISTS images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    client_uuid UUID NOT NULL UNIQUE,

    optimized_storage_path TEXT UNIQUE,
    original_storage_path TEXT UNIQUE,

    -- Imagen optimizada
    optimized_size BIGINT,
    optimized_width INTEGER,
    optimized_height INTEGER,

    -- Imagen original
    original_size BIGINT,
    original_width INTEGER,
    original_height INTEGER,

    optimized_uploaded_at TIMESTAMPTZ,
    original_uploaded_at TIMESTAMPTZ,

    -- Estado de las cargas de imagen
    optimized_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    original_status VARCHAR(20) NOT NULL DEFAULT 'NOT_UPLOADED',

    -- Coordenadas opcionales
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,

    -- Fecha de captura de la imagen
    captured_at TIMESTAMPTZ NOT NULL,

    -- Fecha de recepcion en el servidor
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_images_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_images_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    CONSTRAINT chk_images_optimized_size
        CHECK (optimized_size IS NULL OR optimized_size > 0),

    CONSTRAINT chk_images_optimized_status
        CHECK (optimized_status IN ('PENDING', 'UPLOADED')),

    CONSTRAINT chk_images_original_status
        CHECK (original_status IN ('NOT_UPLOADED', 'PENDING', 'UPLOADED')),

    -- Los datos de archivo deben estar completos cuando se marca UPLOADED
    CONSTRAINT chk_images_optimized_uploaded
        CHECK (
            (optimized_status = 'PENDING'
             AND optimized_storage_path IS NULL
             AND optimized_size IS NULL
             AND optimized_uploaded_at IS NULL)
            OR
            (optimized_status = 'UPLOADED'
             AND optimized_storage_path IS NOT NULL
             AND optimized_size IS NOT NULL
             AND optimized_uploaded_at IS NOT NULL)
        ),

    CONSTRAINT chk_images_original_uploaded
        CHECK (
            (original_status IN ('NOT_UPLOADED', 'PENDING')
             AND original_storage_path IS NULL
             AND original_size IS NULL
             AND original_uploaded_at IS NULL)
            OR
            (original_status = 'UPLOADED'
             AND original_storage_path IS NOT NULL
             AND original_size IS NOT NULL
             AND original_uploaded_at IS NOT NULL)
        )
);


-- ============================================================
-- 4. TABLA: leaf_conditions
-- Catalogo de clases utilizadas por el modelo de IA.
-- ============================================================

CREATE TABLE IF NOT EXISTS leaf_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identificador de clase del modelo de IA
    id_class_model INTEGER NOT NULL UNIQUE,

    name VARCHAR(200) NOT NULL,

    -- Cara de la hoja: haz o enves
    side_leaf VARCHAR(10) NOT NULL,

    pest_taxonomy VARCHAR(255),

    description TEXT,

    title_recommendation_1 VARCHAR(255),
    recommendation_1 TEXT,

    title_recommendation_2 VARCHAR(255),
    recommendation_2 TEXT,

    title_recommendation_3 VARCHAR(255),
    recommendation_3 TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_leaf_conditions_side_leaf
        CHECK (side_leaf IN ('haz', 'enves'))
);


-- ============================================================
-- 5. TABLA: diagnoses
-- Almacena los diagnosticos sincronizados.
-- ============================================================

CREATE TABLE IF NOT EXISTS diagnoses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- UUID generado en Android
    client_uuid UUID NOT NULL UNIQUE,

    -- Una imagen por diagnostico
    id_image BIGINT NOT NULL UNIQUE,

    -- Usuario propietario
    id_user INTEGER NOT NULL,

    -- Fecha de creacion del diagnostico
    created_date TIMESTAMPTZ NOT NULL,

    -- Cara de la hoja analizada
    side_leaf VARCHAR(10) NOT NULL,

    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Solo SYNCED cuando metadata e imagen optimizada esten guardadas
    sync_status VARCHAR(30) NOT NULL DEFAULT 'METADATA_SYNCED',

    CONSTRAINT chk_diagnoses_sync_status
        CHECK (sync_status IN ('METADATA_SYNCED', 'SYNCED')),

    CONSTRAINT fk_diagnoses_image
        FOREIGN KEY (id_image)
        REFERENCES images(id),

    CONSTRAINT fk_diagnoses_user
        FOREIGN KEY (id_user)
        REFERENCES users(id),

    CONSTRAINT chk_diagnoses_side_leaf
        CHECK (side_leaf IN ('haz', 'enves'))
);


-- ============================================================
-- 6. TABLA: detected_conditions
-- Almacena las clases detectadas y sus probabilidades.
-- Un diagnostico puede tener varios sintomas.
-- ============================================================

CREATE TABLE IF NOT EXISTS detected_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_diagnosis BIGINT NOT NULL,

    id_class BIGINT NOT NULL,

    -- Probabilidad del modelo: rango de 0 a 1
    probability NUMERIC(7,6) NOT NULL,

    CONSTRAINT fk_detected_conditions_diagnosis
        FOREIGN KEY (id_diagnosis)
        REFERENCES diagnoses(id),

    CONSTRAINT fk_detected_conditions_class
        FOREIGN KEY (id_class)
        REFERENCES leaf_conditions(id),

    CONSTRAINT chk_condition_probability
        CHECK (probability BETWEEN 0 AND 1),

    -- Evita repetir una clase dentro del mismo diagnostico
    CONSTRAINT uq_detected_conditions_diagnosis_class
        UNIQUE (id_diagnosis, id_class)
);


-- ============================================================
-- 7. INDICES
-- ============================================================

-- Historial de diagnosticos por usuario
CREATE INDEX IF NOT EXISTS idx_diagnoses_user_date
ON diagnoses (id_user, created_date DESC);

-- Busqueda de sintomas por diagnostico
-- La restriccion UNIQUE ya genera un indice para esta combinacion.
-- No se crea otro indice redundante.

-- Busqueda de clases asociadas a sintomas
CREATE INDEX IF NOT EXISTS idx_detected_conditions_class
ON detected_conditions (id_class);

-- Busqueda de clases por nombre
CREATE INDEX IF NOT EXISTS idx_leaf_conditions_name
ON leaf_conditions (name);

-- Imagenes optimizadas pendientes de carga
CREATE INDEX IF NOT EXISTS idx_images_optimized_pending
ON images (id)
WHERE optimized_status = 'PENDING';

-- Diagnosticos con imagen optimizada pendiente
CREATE INDEX IF NOT EXISTS idx_diagnoses_sync_pending
ON diagnoses (id_user, id)
WHERE sync_status = 'METADATA_SYNCED';

-- Imagenes pendientes de respaldo original
CREATE INDEX IF NOT EXISTS idx_images_original_pending
ON images (id)
WHERE original_storage_path IS NULL;

-- Busqueda por fecha de recepcion
CREATE INDEX IF NOT EXISTS idx_images_received_at
ON images (received_at DESC);


-- ============================================================
-- 8. TRIGGER: ACTUALIZACION DE updated_at
-- ============================================================

DROP TRIGGER IF EXISTS trg_leaf_conditions_updated_at
ON leaf_conditions;

CREATE TRIGGER trg_leaf_conditions_updated_at
BEFORE UPDATE ON leaf_conditions
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();


-- ============================================================
-- 9. COMENTARIOS
-- ============================================================

COMMENT ON TABLE images IS
'Imagenes optimizadas y originales asociadas a diagnosticos de hojas.';

COMMENT ON COLUMN images.client_uuid IS
'Identificador UUID generado en Android para evitar duplicados durante la sincronizacion.';

COMMENT ON COLUMN images.optimized_storage_path IS
'Ruta persistente de la imagen optimizada almacenada en el servidor.';

COMMENT ON COLUMN images.original_storage_path IS
'Ruta persistente de la imagen original. NULL indica que aun no se ha respaldado.';

COMMENT ON COLUMN images.optimized_status IS
'PENDING: falta cargar imagen optimizada; UPLOADED: archivo almacenado.';

COMMENT ON COLUMN images.original_status IS
'NOT_UPLOADED o PENDING: original aun no cargado; UPLOADED: original almacenado.';

COMMENT ON COLUMN diagnoses.sync_status IS
'METADATA_SYNCED: falta imagen optimizada; SYNCED: metadata e imagen optimizada almacenadas.';

COMMENT ON COLUMN images.latitude IS
'Latitud opcional del lugar donde se capturo la imagen.';

COMMENT ON COLUMN images.longitude IS
'Longitud opcional del lugar donde se capturo la imagen.';

COMMENT ON TABLE leaf_conditions IS
'Catalogo de clases del modelo de inteligencia artificial y sus recomendaciones.';

COMMENT ON TABLE diagnoses IS
'Diagnosticos de hojas registrados por los usuarios, incluidos los pendientes de imagen optimizada.';

COMMENT ON COLUMN diagnoses.client_uuid IS
'Identificador generado en Android para garantizar sincronizacion idempotente.';

COMMENT ON TABLE detected_conditions IS
'Clases o sintomas detectados por el modelo y sus probabilidades.';


-- ============================================================
-- 10. VERIFICACION DE TABLAS
-- ============================================================

SELECT
    table_name
FROM information_schema.tables
WHERE table_schema = 'public'
AND table_name IN (
    'images',
    'leaf_conditions',
    'diagnoses',
    'detected_conditions'
)
ORDER BY table_name;


-- ============================================================
-- 11. VERIFICACION DE CLAVES PRIMARIAS Y FORANEAS
-- ============================================================

SELECT
    tc.table_name,
    kcu.column_name,
    tc.constraint_type,
    ccu.table_name AS referenced_table,
    ccu.column_name AS referenced_column
FROM information_schema.table_constraints tc
LEFT JOIN information_schema.key_column_usage kcu
    ON tc.constraint_name = kcu.constraint_name
    AND tc.constraint_schema = kcu.constraint_schema
LEFT JOIN information_schema.constraint_column_usage ccu
    ON tc.constraint_name = ccu.constraint_name
    AND tc.constraint_schema = ccu.constraint_schema
WHERE tc.table_schema = 'public'
AND tc.table_name IN (
    'images',
    'leaf_conditions',
    'diagnoses',
    'detected_conditions'
)
AND tc.constraint_type IN ('PRIMARY KEY', 'FOREIGN KEY')
ORDER BY tc.table_name, tc.constraint_type;
