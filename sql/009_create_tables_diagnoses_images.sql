-- ============================================================
-- 5. TABLA: diagnoses
-- Almacena los diagnosticos sincronizados.
-- ============================================================

CREATE TABLE IF NOT EXISTS diagnoses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- UUID generado en Android
    client_uuid UUID NOT NULL UNIQUE,

    -- Una imagen por diagnostico
    id_image BIGINT NOT NULL UNIQUE,

    -- Usuario propietario
    id_user INTEGER NOT NULL,

    -- Fecha de creacion del diagnostico
    created_date TIMESTAMPTZ NOT NULL,

    -- Cara de la hoja analizada
    side_leaf VARCHAR(10) NOT NULL,

    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Solo SYNCED cuando metadata e imagen optimizada esten guardadas
    sync_status VARCHAR(30) NOT NULL DEFAULT 'DATA_SYNCED',

    CONSTRAINT chk_diagnoses_sync_status
        CHECK (sync_status IN ('DATA_SYNCED', 'SYNCED')),

    CONSTRAINT fk_diagnoses_image
        FOREIGN KEY (id_image)
        REFERENCES images(id),

    CONSTRAINT fk_diagnoses_user
        FOREIGN KEY (id_user)
        REFERENCES users(id),

    CONSTRAINT chk_diagnoses_side_leaf
        CHECK (side_leaf IN ('haz', 'enves'))
);


-- ============================================================
-- 6. TABLA: detected_leaf_conditions
-- Almacena las clases detectadas y sus probabilidades.
-- Un diagnostico puede tener varios sintomas.
-- ============================================================

CREATE TABLE IF NOT EXISTS detected_leaf_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_diagnosis BIGINT NOT NULL,

    id_condition BIGINT NOT NULL,

    -- Probabilidad del modelo: rango de 0 a 1
    probability NUMERIC(7,6) NOT NULL,

    CONSTRAINT fk_detected_leaf_conditions_diagnosis
        FOREIGN KEY (id_diagnosis)
        REFERENCES diagnoses(id),

    CONSTRAINT fk_detected_leaf_conditions_class
        FOREIGN KEY (id_condition)
        REFERENCES leaf_conditions(id),

    CONSTRAINT chk_condition_probability
        CHECK (probability BETWEEN 0 AND 1),

    -- Evita repetir una clase dentro del mismo diagnostico
    CONSTRAINT uq_detected_leaf_conditions_diagnosis_class
        UNIQUE (id_diagnosis, id_condition)
);


-- ============================================================
-- 7. INDICES
-- ============================================================

-- Historial de diagnosticos por usuario
CREATE INDEX IF NOT EXISTS idx_diagnoses_user_date
ON diagnoses (id_user, created_date DESC);

-- Busqueda de sintomas por diagnostico
-- La restriccion UNIQUE ya genera un indice para esta combinacion.
-- No se crea otro indice redundante.

-- Busqueda de clases asociadas a sintomas
CREATE INDEX IF NOT EXISTS idx_detected_leaf_conditions_class
ON detected_leaf_conditions (id_condition);

-- Busqueda de clases por nombre
CREATE INDEX IF NOT EXISTS idx_leaf_conditions_name
ON leaf_conditions (name);

-- Imagenes optimizadas pendientes de carga
CREATE INDEX IF NOT EXISTS idx_images_optimized_pending
ON images (id)
WHERE optimized_status = 'PENDING';

-- Diagnosticos con imagen optimizada pendiente
CREATE INDEX IF NOT EXISTS idx_diagnoses_sync_pending
ON diagnoses (id_user, id)
WHERE sync_status = 'METADATA_SYNCED';

-- Imagenes pendientes de respaldo original
CREATE INDEX IF NOT EXISTS idx_images_original_pending
ON images (id)
WHERE original_storage_path IS NULL;

-- Busqueda por fecha de recepcion
CREATE INDEX IF NOT EXISTS idx_images_received_at
ON images (received_at DESC);


-- ============================================================
-- 8. TRIGGER: ACTUALIZACION DE updated_at
-- ============================================================

DROP TRIGGER IF EXISTS trg_leaf_conditions_updated_at
ON leaf_conditions;

CREATE TRIGGER trg_leaf_conditions_updated_at
BEFORE UPDATE ON leaf_conditions
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();


