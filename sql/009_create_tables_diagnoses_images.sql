-- ============================================================
-- 2. FUNCION PARA ACTUALIZAR updated_at
-- ============================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ============================================================
-- 3. TABLA: images
-- Almacena las referencias a las imagenes optimizada y original.
-- ============================================================

CREATE TABLE IF NOT EXISTS images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    client_uuid UUID NOT NULL UNIQUE,

    optimized_storage_path TEXT UNIQUE,
    original_storage_path TEXT UNIQUE,

    -- Imagen optimizada
    optimized_size BIGINT,
    optimized_width INTEGER,
    optimized_height INTEGER,

    -- Imagen original
    original_size BIGINT,
    original_width INTEGER,
    original_height INTEGER,

    optimized_uploaded_at TIMESTAMPTZ,
    original_uploaded_at TIMESTAMPTZ,

    -- Estado de las cargas de imagen
    optimized_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    original_status VARCHAR(20) NOT NULL DEFAULT 'NOT_UPLOADED',

    -- Coordenadas opcionales
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,

    -- Fecha de captura de la imagen
    captured_at TIMESTAMPTZ NOT NULL,

    -- Fecha de recepcion en el servidor
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_images_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_images_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    CONSTRAINT chk_images_optimized_size
        CHECK (optimized_size IS NULL OR optimized_size > 0),

    CONSTRAINT chk_images_optimized_status
        CHECK (optimized_status IN ('PENDING', 'UPLOADED')),

    CONSTRAINT chk_images_original_status
        CHECK (original_status IN ('NOT_UPLOADED', 'PENDING', 'UPLOADED')),

    -- Los datos de archivo deben estar completos cuando se marca UPLOADED
    CONSTRAINT chk_images_optimized_uploaded
        CHECK (
            (optimized_status = 'PENDING'
             AND optimized_storage_path IS NULL
             AND optimized_size IS NULL
             AND optimized_uploaded_at IS NULL)
            OR
            (optimized_status = 'UPLOADED'
             AND optimized_storage_path IS NOT NULL
             AND optimized_size IS NOT NULL
             AND optimized_uploaded_at IS NOT NULL)
        ),

    CONSTRAINT chk_images_original_uploaded
        CHECK (
            (original_status IN ('NOT_UPLOADED', 'PENDING')
             AND original_storage_path IS NULL
             AND original_size IS NULL
             AND original_uploaded_at IS NULL)
            OR
            (original_status = 'UPLOADED'
             AND original_storage_path IS NOT NULL
             AND original_size IS NOT NULL
             AND original_uploaded_at IS NOT NULL)
        )
);


-- ============================================================
-- 4. TABLA: leaf_conditions
-- Catalogo de clases utilizadas por el modelo de IA.
-- ============================================================

CREATE TABLE leaf_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identificador de clase del modelo de IA
    id_class_model INTEGER NOT NULL,

    name TEXT NOT NULL,

    -- Cara de la hoja: haz o enves
    side_leaf VARCHAR(10) NOT NULL,

    pest_taxonomy TEXT,
    description TEXT,

    CONSTRAINT chk_leaf_conditions_side_leaf
        CHECK (side_leaf IN ('haz', 'enves'))
);


CREATE TABLE general_recomendations (
